fn constants_ts() -> String {
    let codes: Vec<&str> = AppErrorCode::ALL.iter().map(|code| code.as_str()).collect();
    let codes = to_string_pretty(&codes).unwrap_or_default();
    let defaults = to_string_pretty(&DEFAULT_SETTINGS).unwrap_or_default();
    let detection_failed = to_string_pretty(DETECTION_FAILED).unwrap_or_default();
    format!(
        "{HEADER}\nimport type {{ AppErrorCode, SettingsDto }} from './types'\n\n\
         /** Every error code, so a code arriving from somewhere untrusted can be checked. */\n\
         export const APP_ERROR_CODES: readonly AppErrorCode[] = {codes}\n\n\
         export function isAppErrorCode(value: unknown): value is AppErrorCode {{\n  \
         return typeof value === 'string' && (APP_ERROR_CODES as readonly string[]).includes(value)\n}}\n\n\
         /** The shipped defaults: what a user with no stored settings sees. */\n\
         export const DEFAULT_SETTINGS: SettingsDto = {defaults}\n\n\
         /** `details.reason` of the `Internal` raised when slicer detection could not run at all. */\n\
         export const DETECTION_FAILED = {detection_failed}\n\n\
         /** The longest search term the project query accepts. */\n\
         export const SEARCH_MAX_LENGTH = {SEARCH_MAX_LENGTH}\n\n\
         /** The largest page a project query may ask for. */\n\
         export const PROJECT_LIMIT_MAX = {PROJECT_LIMIT_MAX}\n\n\
         /** How many tags a remembered filter may hold. */\n\
         export const FILTER_TAGS_MAX = {FILTER_TAGS_MAX}\n"
    )
}

fn index_ts() -> String {
    format!("{HEADER}\nexport * from './constants'\nexport * from './types'\n")
}

/// Every generated file as (file name, content).
pub fn generate() -> Vec<(&'static str, String)> {
    vec![
        ("types.ts", types_ts()),
        ("constants.ts", constants_ts()),
        ("index.ts", index_ts()),
    ]
}

/// The checked-in directory, resolved against this crate's manifest.
pub fn generated_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(GENERATED_DIR)
}

/// Writes the generated files into `dir`, creating it.
pub fn write_to(dir: &Path) -> io::Result<()> {
    fs::create_dir_all(dir)?;
    for (name, content) in generate() {
        fs::write(dir.join(name), content)?;
    }
    Ok(())
}

/// The names of the files in `dir` that are missing or differ from what would be generated now.
/// Line endings are not compared: a Windows checkout may have rewritten them.
pub fn stale_files(dir: &Path) -> Vec<&'static str> {
    generate()
        .into_iter()
        .filter(|(name, content)| {
            fs::read_to_string(dir.join(name))
                .map(|existing| existing.replace("\r\n", "\n") != *content)
                .unwrap_or(true)
        })
        .map(|(name, _)| name)
        .collect()
}

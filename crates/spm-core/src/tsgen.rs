/// Where the checked-in files live, relative to this crate.
pub const GENERATED_DIR: &str = "../../packages/web/src/api/generated";

const HEADER: &str = "// Generated by `pnpm gen:types` (cargo run -p spm-core --example gen_ts) from the\n// Rust contract in crates/spm-core. Do not edit; edit the Rust and regenerate.\n";

fn declaration<T: TS + 'static>(cfg: &Config) -> String {
    let mut out = String::new();
    if let Some(docs) = T::docs() {
        out.push_str(&docs);
    }
    out.push_str("export ");
    out.push_str(&T::decl(cfg));
    out
}

macro_rules! declare {
    ($cfg:expr, $($ty:ty),+ $(,)?) => {
        vec![$(declaration::<$ty>($cfg)),+]
    };
}


//! TypeScript generation: the web package's view of the Rust contract.
//!
//! `cargo run -p spm-core --example gen_ts` (or `pnpm gen:types`) rewrites
//! `packages/web/src/api/generated/`; the files are checked in, and the test
//! `generated_typescript_is_up_to_date` fails when they are stale, so the Rust DTOs and the TS the
//! frontend compiles against cannot drift apart.
//!
//! Two files come out:
//!
//! * `types.ts`: one `export type` per DTO, input type and error type, produced by `ts-rs`.
//! * `constants.ts`: the values the types alone cannot carry (`DEFAULT_SETTINGS`, the error code
//!   list, the validation caps), serialised from the Rust constants so there is one definition.
//!
//! `index.ts` re-exports both.


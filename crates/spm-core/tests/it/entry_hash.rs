#[test]
fn only_the_leading_generated_on_line_is_excluded_and_only_in_that_one_part() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    let b = dir.path().join("b.3mf");
    // The stamp text as a *second* line. What keeps it counted is not the pattern's `^` but the
    // first line being sliced off before the pattern matches at all. Written down because the
    // anchor is the tempting explanation.
    let with_second_line = |at: &str| {
        format!(
            "; PrusaSlicer config\n; generated by PrusaSlicer 2.9.6 on 2026-08-28 at {at} UTC\n"
        )
    };
    write_zip(
        &a,
        &[stored(
            "Metadata/Slic3r_PE.config",
            with_second_line("09:27:30"),
        )],
        None,
    );
    write_zip(
        &b,
        &[stored(
            "Metadata/Slic3r_PE.config",
            with_second_line("09:28:00"),
        )],
        None,
    );
    assert_ne!(entry_hash(&a).unwrap(), entry_hash(&b).unwrap());

    // And the exclusion is keyed on the entry name: the same text anywhere else counts.
    let c = dir.path().join("c.3mf");
    let d = dir.path().join("d.3mf");
    write_zip(
        &c,
        &[stored("Metadata/other.config", prusa_config("09:27:30"))],
        None,
    );
    write_zip(
        &d,
        &[stored("Metadata/other.config", prusa_config("09:28:00"))],
        None,
    );
    assert_ne!(entry_hash(&c).unwrap(), entry_hash(&d).unwrap());
}

#[test]
fn one_changed_byte_anywhere_hashes_differently() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    write_zip(&a, &project(), None);
    let before = entry_hash(&a).unwrap();

    let changes = [
        stored(
            "Metadata/project_settings.config",
            r#"{"layer_height":"0.3"}"#,
        ),
        stored("Metadata/plate_1.png", [1u8, 2, 3, 5]),
        deflated("3D/3dmodel.model", format!("{MODEL_XML} ")),
    ];
    for (i, changed) in changes.iter().enumerate() {
        let b = dir.path().join(format!("b-{i}.3mf"));
        let entries: Vec<ZipInput> = project()
            .into_iter()
            .map(|entry| {
                if entry.name == changed.name {
                    changed.clone()
                } else {
                    entry
                }
            })
            .collect();
        write_zip(&b, &entries, None);
        assert_ne!(entry_hash(&b).unwrap(), before, "{}", changed.name);
        assert_eq!(
            entry_diff(&a, &b).unwrap(),
            diff(&[], &[], &[&changed.name]),
            "{}",
            changed.name
        );
    }
}

#[test]
fn entry_diff_names_what_was_added_and_removed_and_reports_nothing_about_what_is_inside() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    let b = dir.path().join("b.3mf");
    write_zip(&a, &project(), None);
    let mut entries: Vec<ZipInput> = project()
        .into_iter()
        .filter(|entry| entry.name != "Metadata/plate_1.png")
        .collect();
    entries.push(stored("Metadata/cut_information.xml", "<objects/>"));
    write_zip(&b, &entries, None);

    assert_eq!(
        entry_diff(&a, &b).unwrap(),
        diff(
            &["Metadata/cut_information.xml"],
            &["Metadata/plate_1.png"],
            &[]
        )
    );
}

#[test]
fn the_name_and_the_content_are_framed_so_a_shifted_boundary_is_not_a_collision() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    let b = dir.path().join("b.3mf");
    // Concatenating name + bytes without a length makes these two archives identical to hash.
    write_zip(&a, &[stored("a", "bc")], None);
    write_zip(&b, &[stored("ab", "c")], None);

    assert_ne!(entry_hash(&a).unwrap(), entry_hash(&b).unwrap());
}

#[test]
fn a_file_that_is_not_a_zip_is_hashed_as_plain_bytes_and_diffed_under_its_own_name() {
    let dir = tempdir().unwrap();
    fs::create_dir(dir.path().join("returned")).unwrap();
    let launched = dir.path().join("cube.stl");
    let unchanged = dir.path().join("returned").join("cube.stl");
    let changed = dir.path().join("returned").join("changed.stl");
    fs::write(&launched, "solid cube\nendsolid cube\n").unwrap();
    fs::write(&unchanged, "solid cube\nendsolid cube\n").unwrap();
    fs::write(&changed, "solid cube\nendsolid CUBE\n").unwrap();

    assert_eq!(
        entry_hash(&launched).unwrap(),
        entry_hash(&unchanged).unwrap()
    );
    assert_ne!(
        entry_hash(&launched).unwrap(),
        entry_hash(&changed).unwrap()
    );
    // The launch directory's copy of the same file, compared to the source.
    assert_eq!(entry_diff(&launched, &unchanged).unwrap(), no_change());
    fs::write(&unchanged, fs::read(&changed).unwrap()).unwrap();
    assert_eq!(
        entry_diff(&launched, &unchanged).unwrap(),
        diff(&[], &[], &["cube.stl"])
    );
    // Two different basenames read as one file gone and another arrived, which is what they are.
    assert_eq!(
        entry_diff(&launched, &changed).unwrap(),
        diff(&["changed.stl"], &["cube.stl"], &[])
    );
}

#[test]
fn an_empty_file_and_an_empty_archive_both_hash_without_failing() {
    let dir = tempdir().unwrap();
    let empty = dir.path().join("empty.stl");
    fs::write(&empty, "").unwrap();
    let archive = dir.path().join("empty.3mf");
    write_zip(&archive, &[], None);

    // Both come out as SHA-256 over zero bytes, and they are therefore equal. Recorded rather
    // than asserted away: the two hash spaces meet only at nothing-at-all, and change detection
    // only ever compares a path against its own earlier self.
    assert_eq!(entry_hash(&empty).unwrap().len(), 64);
    assert_eq!(entry_hash(&archive).unwrap(), entry_hash(&empty).unwrap());
}


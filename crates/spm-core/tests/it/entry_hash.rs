#[test]
fn an_ordinary_leading_comment_in_slic3r_pe_config_is_not_mistaken_for_the_stamp() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    let b = dir.path().join("b.3mf");
    // `Slic3r_PE.config` is nothing but `; key = value` lines, so a pattern loose enough to mean
    // "any leading comment" would hide the first setting in the file every time it changed.
    write_zip(
        &a,
        &[stored(
            "Metadata/Slic3r_PE.config",
            "; layer_height = 0.2\n; fill = 15%\n",
        )],
        None,
    );
    write_zip(
        &b,
        &[stored(
            "Metadata/Slic3r_PE.config",
            "; layer_height = 0.3\n; fill = 15%\n",
        )],
        None,
    );

    assert_ne!(entry_hash(&a).unwrap(), entry_hash(&b).unwrap());
    assert_eq!(
        entry_diff(&a, &b).unwrap().changed,
        ["Metadata/Slic3r_PE.config"]
    );
}

#[test]
fn a_stamp_with_anything_appended_after_utc_is_left_in_rather_than_guessed_at() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    let b = dir.path().join("b.3mf");
    // Not a measured line: the point is the direction of the error. An unrecognised first line
    // counts towards the hash, so an unexpected format costs a spurious "this changed" and never a
    // missed one.
    let stamped =
        |at: &str| format!("; generated by PrusaSlicer 2.9.6 at {at} UTC (dev)\n; x = 1\n");
    write_zip(
        &a,
        &[stored("Metadata/Slic3r_PE.config", stamped("09:27:30"))],
        None,
    );
    write_zip(
        &b,
        &[stored("Metadata/Slic3r_PE.config", stamped("09:28:00"))],
        None,
    );

    assert_ne!(entry_hash(&a).unwrap(), entry_hash(&b).unwrap());
}

#[test]
fn a_non_zip_file_larger_than_one_read_chunk_is_hashed_whole() {
    let dir = tempdir().unwrap();
    let path = dir.path().join("cube.stl");
    let shifted = dir.path().join("shifted.stl");
    // Past the read chunk size, so the streamed read really does loop. Every other non-zip case
    // here is a few dozen bytes and leaves the partial-final-chunk slice unexercised.
    let bytes: Vec<u8> = (0..2 * (1usize << 20) + 513)
        .map(|i| (i.wrapping_mul(17) & 0xff) as u8)
        .collect();
    fs::write(&path, &bytes).unwrap();

    // Against an independent hash of the same bytes in one go, not against itself.
    let expected: String = Sha256::digest(&bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    assert_eq!(entry_hash(&path).unwrap(), expected);

    // And the very last byte, which is what a mis-sliced final chunk would drop or duplicate.
    let mut tail = bytes.clone();
    *tail.last_mut().unwrap() ^= 0xff;
    fs::write(&shifted, &tail).unwrap();
    assert_ne!(entry_hash(&shifted).unwrap(), entry_hash(&path).unwrap());
}

#[test]
fn a_slic3r_pe_config_with_crlf_line_endings_still_has_its_stamp_excluded() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    let b = dir.path().join("b.3mf");
    // PrusaSlicer is a Windows-first application and nothing measured pinned its line endings, so
    // the CR handling is not decoration: without it the stamp line keeps a trailing `\r`, fails
    // the pattern, and every save of an unchanged project reads as changed.
    let crlf = |at: &str| {
        format!(
            "; generated by PrusaSlicer 2.9.6 on 2026-08-28 at {at} UTC\r\n; layer_height = 0.2\r\n"
        )
    };
    write_zip(
        &a,
        &[stored("Metadata/Slic3r_PE.config", crlf("09:27:30"))],
        None,
    );
    write_zip(
        &b,
        &[stored("Metadata/Slic3r_PE.config", crlf("09:28:00"))],
        None,
    );

    assert_eq!(entry_hash(&a).unwrap(), entry_hash(&b).unwrap());
    assert_eq!(entry_diff(&a, &b).unwrap(), no_change());
}

//! Ports `entry-hash.test.ts`.

use std::fs;
use std::path::Path;

use sha2::{Digest, Sha256};
use spm_core::files::entry_hash::{EntryDiff, entry_diff, entry_hash};
use tempfile::tempdir;

use crate::fixtures::{
    MODEL_XML, ZipInput, deflated, patch_zip_headers, set_u16, stored, write_zip,
};

/// The wall-clock DOS stamp the three Bambu-lineage slicers write on every save.
fn stamp_times(path: &Path, time: u16, date: u16) {
    patch_zip_headers(path, |entry| {
        set_u16(entry.file, entry.central_at + 12, time);
        set_u16(entry.file, entry.central_at + 14, date);
        set_u16(entry.file, entry.local_at + 10, time);
        set_u16(entry.file, entry.local_at + 12, date);
    });
}

fn project() -> Vec<ZipInput> {
    vec![
        stored("[Content_Types].xml", "<Types/>"),
        deflated("3D/3dmodel.model", MODEL_XML),
        stored(
            "Metadata/project_settings.config",
            r#"{"layer_height":"0.2"}"#,
        ),
        stored("Metadata/plate_1.png", [1u8, 2, 3, 4]),
    ]
}

fn prusa_config(at: &str) -> String {
    format!(
        "; generated by PrusaSlicer 2.9.6 on 2026-08-28 at {at} UTC\n; layer_height = 0.2\n; fill_density = 15%\n"
    )
}

fn diff(added: &[&str], removed: &[&str], changed: &[&str]) -> EntryDiff {
    let own = |names: &[&str]| names.iter().map(|name| (*name).to_owned()).collect();
    EntryDiff {
        added: own(added),
        removed: own(removed),
        changed: own(changed),
    }
}

fn no_change() -> EntryDiff {
    diff(&[], &[], &[])
}

#[test]
fn two_saves_of_identical_content_with_different_zip_timestamps_hash_equal() {
    let dir = tempdir().unwrap();
    let a = dir.path().join("a.3mf");
    let b = dir.path().join("b.3mf");
    write_zip(&a, &project(), None);
    write_zip(&b, &project(), None);
    stamp_times(&a, 0x5c2b, 0x5d1c);
    stamp_times(&b, 0x61f0, 0x5d1d);
    // The container really did change: this is the measured failure of a whole-file hash.
    assert_ne!(fs::read(&a).unwrap(), fs::read(&b).unwrap());

    assert_eq!(entry_hash(&a).unwrap(), entry_hash(&b).unwrap());
    assert_eq!(entry_diff(&a, &b).unwrap(), no_change());
}

